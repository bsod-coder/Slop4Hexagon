// Helper to surface Git commit in BuildConfig (optional)
val gitCommit: String = try {
    Runtime.getRuntime().exec(arrayOf("git", "rev-parse", "--short", "HEAD"))
        .inputStream.bufferedReader().readLine() ?: "unknown"
} catch (_: Exception) { "unknown" }

android.buildTypes.forEach { type ->
    type.buildConfigField("String", "GIT_COMMIT", "\"$gitCommit\"")
}
